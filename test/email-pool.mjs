import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { assurivoFeedUrl, createEmailPool, parseEmailPoolText, redactMailboxUrl } from "../src/email-pool.mjs";

assert.equal(redactMailboxUrl("https://user:secret@mail.example:8443/latest?token=hidden"), "https://mail.example:8443/latest");
const parsed = parseEmailPoolText("a@example.com----https://mail.example/a\n# comment\nb@example.com----https://mail.example/b----{\"email\":\"b@example.com\"}\nbad line");
assert.equal(parsed.entries.length, 2);
assert.equal(parsed.errors.length, 1);
const assurivo = parseEmailPoolText("Name@icloud.com----query-code-secret\n# skip\nbroken line", "assurivo");
assert.equal(assurivo.entries.length, 1);
assert.equal(assurivo.errors.length, 1);
assert.equal(assurivo.entries[0].provider, "assurivo");
assert.equal(assurivo.entries[0].mailApiUrl, assurivoFeedUrl("Name@icloud.com", "query-code-secret"));
assert.equal(assurivo.entries[0].mailApiUrl.includes("pwd=query-code-secret"), true);

const root = await fs.mkdtemp(path.join(os.tmpdir(), "tosub2-email-pool-"));
const pool = createEmailPool({ filePath: path.join(root, "email-pool.json") });
const imported = await pool.importText("a@example.com----https://mail.example/a?token=secret\nb@example.com----https://mail.example/b?token=secret\n");
assert.equal(imported.imported, 2);
assert.equal(JSON.stringify(imported).includes("secret"), false);
const first = await pool.claim({ jobId: "job-1", currentEmail: "current@example.com", blockedEmails: ["current@example.com"] });
const second = await pool.claim({ jobId: "job-2", currentEmail: "current@example.com", blockedEmails: [] });
assert.equal(first.email, "a@example.com");
assert.equal(second.email, "b@example.com");
assert.equal(await pool.claim({ jobId: "job-3", currentEmail: "current@example.com", blockedEmails: [] }), null);
await pool.release(first.email, "someone-else");
assert.equal((await pool.summary()).available, 0);
await pool.release(first.email, "job-1");
assert.equal((await pool.summary()).available, 1);
await pool.block(first.email, "job-1");
assert.equal((await pool.summary()).items.find((item) => item.email === "a@example.com").status, "blocked");
await pool.consume(second.email, "job-2", "current@example.com");
assert.equal((await pool.summary()).items.find((item) => item.email === "b@example.com").status, "used");
const assurivoImported = await pool.importText("Name@icloud.com----query-code-secret", "assurivo");
assert.equal(assurivoImported.imported, 1);
assert.equal(assurivoImported.items.find((item) => item.email === "Name@icloud.com").provider, "assurivo");
assert.equal(JSON.stringify(assurivoImported).includes("query-code-secret"), false);
assert.equal((await pool.summary()).items.find((item) => item.email === "Name@icloud.com").mailbox, "https://assurivo.com/console/feed.php");
const storedMailbox = await pool.mailboxFor("Name@icloud.com");
assert.equal(storedMailbox.provider, "assurivo");
assert.match(storedMailbox.mailApiUrl, /pwd=query-code-secret/);
assert.equal(await pool.mailboxFor("missing@example.com"), null);
const removed = await pool.remove(["a@example.com", "b@example.com"]);
assert.equal(removed.deleted, 2);
const mode = (await fs.stat(path.join(root, "email-pool.json"))).mode & 0o777;
assert.equal(mode, 0o600);
console.log("PASS: email pool");
